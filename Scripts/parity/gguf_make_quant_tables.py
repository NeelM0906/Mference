#!/usr/bin/env python3
"""Generate GGUFQuantTables.swift from llama.cpp's ggml-common.h.

The i-quant grids, sign table and IQ4_NL value table are data that a GGUF
reader cannot derive: they must be the exact tables llama.cpp dequantizes with.
This script parses them out of the pinned source instead of anyone typing them,
and fails closed if the source file is not the pinned one.

    python3 Scripts/parity/gguf_make_quant_tables.py <llama.cpp>/ggml/src/ggml-common.h

writes Sources/Mference/Infrastructure/ModelIO/GGUFQuantTables.swift. The
emitted `tableDigest` is the SHA-256 of the tables' little-endian bytes in the
order below; GGUFQuantTablesTests recomputes it.

Pinned: llama.cpp b1b770d90d94cad9e9ea5b993bdbc383a522fb28 (v1.0.0).
"""

import hashlib
import pathlib
import re
import struct
import sys

PINNED_COMMIT = "b1b770d90d94cad9e9ea5b993bdbc383a522fb28"
PINNED_SHA256 = "0061131b615c5721fc88a78feeb22c1f8c450f1c2646a317d80796a653bf595c"

# (C name, Swift name, element type, count, struct format, Swift type)
TABLES = [
    ("ksigns_iq2xs", "ksignsIQ2XS", "uint8_t", 128, "<B", "UInt8"),
    ("kvalues_iq4nl", "kvaluesIQ4NL", "int8_t", 16, "<b", "Int8"),
    ("iq3xxs_grid", "iq3xxsGrid", "uint32_t", 256, "<I", "UInt32"),
    ("iq2s_grid", "iq2sGrid", "uint64_t", 1024, "<Q", "UInt64"),
]

REPO = pathlib.Path(__file__).resolve().parents[2]
OUT = REPO / "Sources/Mference/Infrastructure/ModelIO/GGUFQuantTables.swift"


def parse_table(text: str, name: str, ctype: str, count: int) -> list[int]:
    m = re.search(
        r"GGML_TABLE_BEGIN\(\s*" + re.escape(ctype) + r"\s*,\s*" + re.escape(name)
        + r"\s*,\s*(\w+)\s*\)(.*?)GGML_TABLE_END\(\)",
        text,
        re.S,
    )
    if not m:
        sys.exit(f"table {name} ({ctype}) not found")
    if m.group(1) != str(count):
        sys.exit(f"table {name}: declared size {m.group(1)}, expected {count}")
    body = re.sub(r"//[^\n]*", "", m.group(2))
    values = [int(tok, 0) for tok in re.findall(r"-?(?:0x[0-9a-fA-F]+|\d+)", body)]
    if len(values) != count:
        sys.exit(f"table {name}: parsed {len(values)} values, expected {count}")
    return values


def swift_literal(values: list[int], swift_type: str, per_line: int) -> str:
    if swift_type in ("UInt32", "UInt64"):
        width = 8 if swift_type == "UInt32" else 16
        items = [f"0x{v:0{width}x}" for v in values]
    else:
        items = [str(v) for v in values]
    lines = []
    for i in range(0, len(items), per_line):
        lines.append("        " + ", ".join(items[i:i + per_line]) + ",")
    return "\n".join(lines)


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = pathlib.Path(sys.argv[1])
    raw = src.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != PINNED_SHA256:
        sys.exit(f"{src}: SHA-256 {digest} is not the pinned {PINNED_SHA256}")
    text = raw.decode()

    parsed = {name: parse_table(text, name, ctype, count) for name, _, ctype, count, _, _ in TABLES}

    # Structural checks the decoders rely on.
    signs = parsed["ksigns_iq2xs"]
    for i, s in enumerate(signs):
        if s & 0x7F != i or bin(s).count("1") % 2 != 0:
            sys.exit(f"ksigns_iq2xs[{i}] = {s} is not the even-parity extension of {i}")

    table_bytes = b"".join(
        b"".join(struct.pack(fmt, v) for v in parsed[name]) for name, _, _, _, fmt, _ in TABLES
    )
    table_digest = hashlib.sha256(table_bytes).hexdigest()

    per_line = {"UInt8": 16, "Int8": 16, "UInt32": 6, "UInt64": 4}
    blocks = []
    for name, swift_name, _, count, _, swift_type in TABLES:
        blocks.append(
            f"    /// `{name}` ({count} entries).\n"
            f"    public static let {swift_name}: [{swift_type}] = [\n"
            f"{swift_literal(parsed[name], swift_type, per_line[swift_type])}\n"
            f"    ]\n"
        )

    OUT.write_text(
        "// GENERATED by Scripts/parity/gguf_make_quant_tables.py; do not edit.\n"
        f"// Source: llama.cpp {PINNED_COMMIT}, ggml/src/ggml-common.h\n"
        f"// (SHA-256 {PINNED_SHA256}).\n"
        "//\n"
        "// The tables below are copied from ggml, which carries this notice:\n"
        "//\n"
        "//   MIT License\n"
        "//   Copyright (c) 2023-2026 The ggml authors\n"
        "//\n"
        "// The full license text is in LICENSE-GGML.\n"
        "\n"
        "/// GGUF i-quant grids and value tables, exactly as llama.cpp dequantizes\n"
        "/// with them (WS4 U1 §1). `tableDigest` is the SHA-256 of the tables'\n"
        "/// little-endian bytes in declaration order.\n"
        "public enum GGUFQuantTables {\n"
        f"    public static let sourceCommit = \"{PINNED_COMMIT}\"\n"
        f"    public static let tableDigest = \"{table_digest}\"\n"
        "\n"
        + "\n".join(blocks)
        + "}\n"
    )
    print(f"wrote {OUT.relative_to(REPO)} (table digest {table_digest})")


if __name__ == "__main__":
    main()
